package com.annasetu.entity.enums;

/**
 * Responsibility:
 * Represents the occasion or personal milestone commemorated by the donor during a meal sponsorship.
 *
 * Domain Context:
 * - BIRTHDAY: Sponsoring a meal to celebrate a birthday with children or seniors.
 * - ANNIVERSARY: Marriage or business anniversary commemoration.
 * - MEMORIAL: In memory of deceased loved ones or ancestors.
 * - FESTIVAL: Cultural or national celebration (e.g., Diwali, Eid, Christmas, New Year).
 * - OTHER: Gratitude donation, general charity, or personal achievement.
 *
 * Interview Talking Point:
 * Allows organizations to personalize meal announcements or prayer sessions
 * and helps donors look back at their life events in booking history.
 */
public enum Occasion {
    BIRTHDAY,
    ANNIVERSARY,
    MEMORIAL,
    FESTIVAL,
    OTHER
}
